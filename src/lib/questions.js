export const makeMcq = (exclude) => {
  let i;
  do { i = Math.floor(Math.random() * MCQ.length); } while (i === exclude && MCQ.length > 1);
  const m = MCQ[i];
  return { kind: "mcq", idx: i, q: m.q, e: m.e, opts: shuffle(m.o.map((t, k) => ({ t, ok: k === 0 }))) };
};
