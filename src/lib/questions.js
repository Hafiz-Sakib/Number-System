/* সব পদ্ধতিতেই নিখুঁতভাবে শেষ হয় এমন ভগ্নাংশ (হর 2 এর ঘাত) */
const FR8 = [[1n, 2n], [1n, 4n], [3n, 4n], [1n, 8n], [3n, 8n], [5n, 8n], [7n, 8n]];
const FR16 = [...FR8, [1n, 16n], [3n, 16n], [5n, 16n], [7n, 16n], [9n, 16n], [11n, 16n], [13n, 16n], [15n, 16n]];

export function makeConvert(level) {
  const pairs = BASES.flatMap((f) => BASES.filter((t) => t !== f).map((t) => [f, t]));
  const [from, to] = pick(pairs);
  const max = level === "easy" ? 31 : level === "medium" ? 255 : 4095;
  const min = level === "hard" ? 16 : 3;
  const chance = level === "easy" ? 0 : level === "medium" ? 0.35 : 0.65;
  const iv = BigInt(ri(min, max));
  let r = rat(iv);
  if (Math.random() < chance) { const [n, d] = pick(level === "hard" ? FR16 : FR8); r = rat(iv * d + n, d); }
  return { kind: "convert", from, to, text: str(r, from), expect: str(r, to), base: to };
}

export function makeArith(level) {
  const base = level === "easy" ? 2 : pick([2, 8, 16, 2]);
  const op = level === "easy" ? pick(["+", "-"]) : level === "medium" ? pick(["+", "-", "*"]) : pick(["+", "-", "*", "/"]);
  const lim = level === "easy" ? 31 : level === "medium" ? 100 : 255;
  let x = ri(3, lim), y = ri(2, Math.max(3, Math.floor(lim / (op === "*" ? 8 : 2))));
  if (op === "-" && y > x) [x, y] = [y, x];
  if (op === "/") { y = ri(2, 12); x = y * ri(2, 20); }
  const a = str(rat(BigInt(x)), base), b = str(rat(BigInt(y)), base);
  return { kind: "arith", base, op, a, b, expect: calc(a, b, op, base, "direct").text };
}

const flip = (s) => [...s].map((c) => (c === "0" ? "1" : "0")).join("");
export function makeComplement(level) {
  const n = level === "easy" ? 4 : level === "medium" ? 6 : 8;
  const sub = pick(["ones", "twos", "twos", "sub"]);
  const rnd = () => ri(1, 2 ** n - 1);
  if (sub === "sub") {
    const A = rnd().toString(2).padStart(n, "0"), B = rnd().toString(2).padStart(n, "0");
    return { kind: "comp", sub, n, a: A, b: B, base: 2, expect: calc(A, B, "-", 2, "complement").text };
  }
  const x = rnd().toString(2).padStart(n, "0");
  const ones = flip(x);
  const twos = ((2 ** n - parseInt(x, 2)) % 2 ** n).toString(2).padStart(n, "0");
  return { kind: "comp", sub, n, x, ones, twos, base: 2, expect: sub === "ones" ? ones : twos };
}

